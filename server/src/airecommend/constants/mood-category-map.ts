const GROUP_LABELS: Record<MoodGroup, string> = {
  rest: '휴식/안정',
  blue: '불안/슬픔',
  energy: '활기/기쁨',
  mood: '감성/추억',
  drive: '변화/동기',
};

// LLM 프롬프트(ai.service.ts::generateBookRecommendations)의 [분석 규칙]이
// '휴식/안정' 같은 그룹 라벨을 기준으로 분기하는데, 클라이언트가 실제로
// 보내는 currentMood는 "막막한" 같은 구체적 형용사라서 그 라벨이 프롬프트
// 입력 어디에도 안 나타나는 문제가 있었다(LLM이 형용사→그룹을 스스로
// 추측해야 했음). 이 함수로 그룹 라벨을 직접 구해서 프롬프트에 같이
// 넘겨준다. (이건 형용사 단위가 아니라 그룹 단위 하드 룰이라
// ADJECTIVE_TO_GROUP을 그대로 씀 — getCategoriesForMood와는 별개 관심사.)
export function getMoodGroupLabel(currentMood: string): string | null {
  const group = ADJECTIVE_TO_GROUP[currentMood.trim()];
  return group ? GROUP_LABELS[group] : null;
}
